/** Romanised script: match at a word start. Devanagari or symbols: substring. */
export function hasWord(text: string, word: string): boolean {
  if (/[^ -~]/.test(word)) return text.includes(word); // non-ASCII (Devanagari, ₹): substring
  const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[^a-z])${escaped}`).test(text);
}

export function hasAny(text: string, words: readonly string[]): boolean {
  return words.some((w) => hasWord(text, w));
}
